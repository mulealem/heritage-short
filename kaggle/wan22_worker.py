"""Kaggle worker: Wan 2.2 TI2V-5B image-to-video for every shot.

Runs on Kaggle GPU (T4). Reads kaggle/manifest_shots.json (generated by
`make shots`) and the keyframes you uploaded, writes one mp4 per shot and a
kaggle_runs.jsonl you copy back into the repo.

NOTE: written against the Wan2.2 diffusers usage pattern; if the API moved,
check the current model card (https://huggingface.co/Wan-AI/Wan2.2-TI2V-5B)
and record what changed in FAILURES.md.
"""
import base64
import json
import time

import torch
from diffusers import WanImageToVideoPipeline
from diffusers.utils import export_to_video, load_image

MANIFEST = "/kaggle/working/manifest_shots.json"
KEYFRAMES = "/kaggle/working/keyframes"
OUTDIR = "/kaggle/working/shotclips"
RUNS = "/kaggle/working/kaggle_runs.jsonl"


def log(rec):
    with open(RUNS, "a") as f:
        f.write(json.dumps(rec) + "\n")


def main():
    manifest = json.load(open(MANIFEST))
    pipe = WanImageToVideoPipeline.from_pretrained(
        manifest["model"], torch_dtype=torch.bfloat16)
    pipe.enable_model_cpu_offload()  # T4s have 16 GB; offload keeps headroom

    for shot in manifest["shots"]:
        t0 = time.time()
        rec = {"ts": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
               "stage": "shots", "model": manifest["model"],
               "shot": shot["id"], "seed": shot["seed"], "status": "started"}
        log(rec)
        try:
            image = load_image(f"{KEYFRAMES}/{shot['id']}.png").convert("RGB")
            frames = int(shot["seconds"] * manifest["fps"]) // 4 * 4 + 1  # 4n+1 frames
            generator = torch.Generator(device="cuda").manual_seed(shot["seed"])
            out = pipe(
                image=image,
                prompt=shot["prompt"],
                num_frames=min(frames, 121),      # model caps at 121 frames (5 s @ 24 fps)
                guidance_scale=5.0,
                num_inference_steps=30,           # start low; quality knob for experiments
                generator=generator,
            ).frames[0]
            export_to_video(out, f"{OUTDIR}/{shot['id']}.mp4", fps=manifest["fps"])
            rec.update(status="ok", latency_s=round(time.time() - t0, 1),
                       output=f"shotclips/{shot['id']}.mp4")
        except Exception as e:  # keep going — save-as-you-go on quota-limited GPUs
            rec.update(status="error", note=str(e)[:300], latency_s=round(time.time() - t0, 1))
        log(rec)
        print(rec)


if __name__ == "__main__":
    main()
