"""Stage: music — ACE-Step score via Kaggle, with a local ambient-pad placeholder.

Radio-cut rule from the brief: narration over placeholder music is a valid and
useful cut, so this stage always produces something playable.

Real mode: outputs/music/score_final.mp3 must exist (generated by the Kaggle
ACE-Step worker from kaggle/manifest_music.json, after you audition the three
candidates and pick one as score_final).
Mock mode: a quiet generated pad (ffmpeg sines), full film length.
"""
import json
import sys
from pathlib import Path

from pipeline import common


def main():
    sb = common.load_storyboard()
    mus = sb["music"]
    meta = sb["meta"]
    total = common.film_duration(sb)
    out_dir = common.stage_dir("music")

    # Manifest for the Kaggle ACE-Step worker.
    mf = {
        "caption": mus["caption"],
        "bpm": mus["bpm"],
        "key": mus["key"],
        "instrumental": mus.get("instrumental", True),
        "seconds": total,
        "candidates": mus.get("candidates", 3),
        "seeds": [int(mus.get("seed", 42)) + i for i in range(mus.get("candidates", 3))],
        "lyrics": mus.get("lyrics", ""),
    }
    mf_path = common.ROOT / "kaggle" / "manifest_music.json"
    mf_path.parent.mkdir(exist_ok=True)
    mf_path.write_text(json.dumps(mf, indent=1))

    final = out_dir / "score_final.wav"
    ph = out_dir / "score_placeholder.wav"
    candidates = sorted(out_dir.glob("candidate_*.mp3")) + sorted(out_dir.glob("candidate_*.wav"))

    if final.exists() and common.probe_duration(final):
        d = common.probe_duration(final)
        common.log_call(stage="music", model="ace-step-1.5", seed=None,
                        params={"mode": "chosen-final", "seconds": d},
                        status="ok", output=str(final),
                        note="score_final present (chosen on Kaggle)")
        print("music: using chosen score_final.wav (%.1fs)" % d)
    elif candidates:
        common.log_call(stage="music", model="ace-step-1.5", status="skip",
                        note="%d candidates found; audition and pick one" % len(candidates))
        print("music: %d candidates in %s — audition them, copy the winner to "
              "outputs/music/score_final.wav (and note WHY in EXPERIMENTS.md)"
              % (len(candidates), out_dir))
    elif not (ph.exists() and common.probe_duration(ph)):
        _placeholder(ph, total, meta["title"])
        common.log_call(stage="music", model="mock-pad", status="mock",
                        params={"seconds": total}, output=str(ph),
                        note="placeholder pad; real score needs Kaggle ACE-Step run")
        print("music: placeholder pad (%.0fs) — clearly not the final score. "
              "Run the Kaggle ACE-Step worker (kaggle/README.md) for the real thing."
              % total)
    else:
        print("music: keeping existing placeholder pad; real score needs Kaggle run "
              "then candidates -> score_final.wav")

    print("kaggle manifest written -> %s" % mf_path)


def _placeholder(final_path, seconds, title):
    """Quiet ambient pad: three detuned sines + slow tremolo, faded in/out."""
    from pipeline import common as c
    dur = int(seconds) + 1
    args = ["-f", "lavfi", "-i", "sine=frequency=110:duration=%d" % dur,
            "-f", "lavfi", "-i", "sine=frequency=164.81:duration=%d" % dur,
            "-f", "lavfi", "-i", "sine=frequency=220:duration=%d" % dur,
            "-filter_complex",
            "[0][1][2]amix=inputs=3,tremolo=f=0.25:d=0.7,"
            "volume=0.25,afade=t=in:st=0:d=2,afade=t=out:st=%d:d=3[out]"
            % max(0, int(seconds) - 3),
            "-map", "[out]", "-ar", "48000", "-ac", "2", str(final_path)]
    c.run_ffmpeg(args, stage="music", note="placeholder ambient pad for %s" % title)


if __name__ == "__main__":
    main()
